/// Time frame for records
///
/// ## Daily Records Strategy
///
/// **Purpose:** Daily records provide fine-grained data for monthly charts in StatisticsView.
/// They are an internal implementation detail, NOT exposed to users in the UI.
///
/// **Lifecycle:**
/// 1. **Creation:** Generated by `RecordHistoryManager.updateAllDailyRecords()` which is called
///    from `RecordManager.updateDailyRecords()` each time a location update occurs
/// 2. **Storage:** Persisted in Core Data with `timeFrame = "Daily"`
/// 3. **Usage:** Loaded by `StatisticsView` to build day-by-day charts for "This Month" view
/// 4. **Cleanup:** Old daily records (>60 days) are deleted by `cleanupOldDailyRecords()`
///    which is called from `StatisticsView.onAppear` and after photo imports
///
/// **Why Hidden:**
/// - Users don't need to see "daily best" records - they care about monthly/yearly/lifetime
/// - Daily records are ephemeral - only kept for recent months to support charts
/// - Showing them would clutter the UI and confuse users
///
/// **Data Flow:**
/// ```
/// LocationUpdate → RecordManager.updateRecords()
///                → RecordManager.updateDailyRecords()
///                → RecordHistoryManager.updateAllDailyRecords()
///                → Core Data (timeFrame="Daily")
///                → StatisticsView.loadStatistics()
///                → Monthly charts
/// ```
/// NOTE: WidgetTimeFrame in GeoRecordsWidget.swift duplicates month/year/allTime cases.
/// When modifying these cases, update BOTH enums to stay in sync.
enum TimeFrame: String, CaseIterable {
    case daily = "Daily"      // Hidden daily extremes for chart granularity (see doc comment above)
    case month = "Monthly"    // Widget uses "This Month" display but matches this rawValue
    case year = "Yearly"      // Widget uses "This Year" display but matches this rawValue
    case allTime = "Lifetime" // Matches widget exactly

    /// Initialize from deep link URL parameter (e.g., "monthly", "yearly", "allTime")
    init?(deepLinkParam param: String) {
        switch param {
        case "monthly": self = .month
        case "yearly": self = .year
        case "allTime": self = .allTime
        default: return nil
        }
    }

    /// Label for record detail views (e.g., "Monthly Record")
    var recordLabel: String {
        "\(rawValue) Record"
    }

    /// Single-letter abbreviation for compact UI display
    var abbreviation: String {
        switch self {
        case .daily: return "D"
        case .month: return "M"
        case .year: return "Y"
        case .allTime: return "L"
        }
    }

    /// Color associated with this timeframe
    var color: Color {
        switch self {
        case .daily: return .gray
        case .month: return .green
        case .year: return .orange
        case .allTime: return .blue
        }
    }

    /// Sort order for displaying timeframes (Monthly first, then Yearly, then Lifetime)
    var sortOrder: Int {
        switch self {
        case .daily: return -1  // Not shown in UI
        case .month: return 0
        case .year: return 1
        case .allTime: return 2
        }
    }

    /// Whether this timeframe should be shown in the UI picker
    var isUserVisible: Bool {
        switch self {
        case .daily: return false
        case .month, .year, .allTime: return true
        }
    }

    /// User-visible timeframes for pickers
    static var userVisibleCases: [TimeFrame] {
        return allCases.filter { $0.isUserVisible }
    }

    /// The most significant timeframe in a set (lifetime > yearly > monthly > daily).
    /// Used to pick the single "biggest achievement" notification when one location
    /// event beats records in several timeframes at once.
    static func mostSignificant(of timeFrames: Set<TimeFrame>) -> TimeFrame? {
        return timeFrames.max { $0.sortOrder < $1.sortOrder }
    }
}

/// Record type enum for type safety and comparison logic.
/// NOTE: WidgetRecordType in GeoRecordsWidget.swift duplicates the geographic extreme cases.
/// When modifying north/south/east/west/up/fromHome cases, update BOTH enums to stay in sync.
enum RecordType: String, CaseIterable {
    case north = "Furthest North"
    case south = "Furthest South"
    case east = "Furthest East"
    case west = "Furthest West"
    case up = "Furthest Up"
    case fromHome = "Furthest from Home"
    case state = "New State"
    case country = "New Country"
    case continent = "New Continent"

    /// Whether this is a geographical extreme record (vs. region visit)
    var isGeographicExtreme: Bool {
        switch self {
        case .north, .south, .east, .west, .up, .fromHome:
            return true
        case .state, .country, .continent:
            return false
        }
    }

    /// Whether this is a region visit record
    var isRegionVisit: Bool {
        return !isGeographicExtreme
    }

    /// Whether this record type uses ascending comparison (higher is better)
    /// Only applies to geographic extremes
    var isAscending: Bool {
        switch self {
        case .north, .east, .up, .fromHome:
            return true  // Higher values are better
        case .south, .west:
            return false  // Lower values are better
        case .state, .country, .continent:
            return true  // Earlier timestamp is "better" (first visit)
        }
    }

    /// Determine if a new value should replace an existing record
    func shouldReplace(newValue: Double, oldValue: Double) -> Bool {
        return isAscending ? newValue > oldValue : newValue < oldValue
    }

    /// All record type strings for compatibility
    static var allTypeStrings: [String] {
        return RecordType.allCases.map { $0.rawValue }
    }

    /// Get record type from string (for backward compatibility)
    static func from(string: String) -> RecordType? {
        return RecordType.allCases.first { $0.rawValue == string }
    }
}

